def build_data_product_registry() -> dict[str, Any]:
    """Return PetroGrid data product registry payload (v0.1)."""
    return {
        "registry_version": "0.1",
        "product_id": "petrogrid",
        "product_name": "PetroGrid",
        "groups": {
            "api_data_products": _api_data_products(),
            "bronze_data_products": _bronze_data_products(),
            "gold_data_products": _gold_data_products(),
        },
        "excluded_layers": {
            "silver": {
                "status": "not_implemented",
                "reason": "Silver schema exists in migrations but is not persisted by the ingestion pipeline.",
                "active_products_exposed": False,
            }
        },
        "generated_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
    }
