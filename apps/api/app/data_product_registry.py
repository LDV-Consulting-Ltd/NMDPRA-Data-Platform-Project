def _product(
    *,
    product_id: str,
    product_name: str,
    description: str,
    domain: str,
    source_layer: str,
    backing_api: Optional[str],
    backing_table: Optional[str],
    freshness_source: str,
    quality_source: str,
    status: str,
    limitations: str,
    api_backed: bool,
    table_backed: bool,
    gold_backed: bool,
    tanna_sync_ready: bool,
) -> dict[str, Any]:
    return {
        "product_id": product_id,
        "product_name": product_name,
        "description": description,
        "domain": domain,
        "source_layer": source_layer,
        "backing_api": backing_api,
        "backing_table": backing_table,
        "freshness_source": freshness_source,
        "quality_source": quality_source,
        "status": status,
        "limitations": limitations,
        "api_backed": api_backed,
        "table_backed": table_backed,
        "gold_backed": gold_backed,
        "tanna_sync_ready": tanna_sync_ready,
    }


